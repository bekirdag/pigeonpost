#!/usr/bin/env bash
# Reproducibly build the web inbox bundle into site-inbox/vendor/groupcrypto/.
#
# Inputs are pinned: Rust 1.91.1 (rust-toolchain.toml), Cargo.lock (--locked), and
# wasm-bindgen-cli 0.2.128 (must equal the wasm-bindgen crate version). Host paths are remapped,
# so output does not depend on the checkout location. The reference build host is x86_64 Linux:
# Cargo folds `rustc -vV` (which names the host triple) into crate metadata hashes, so a macOS
# build lays the wasm out differently (same code and strings, different bytes). The committed
# bundle is the Linux build; CI rebuilds it on ubuntu-24.04 and compares. On another host:
#   docker run --rm -v "$PWD":/src -w /src/crates/pigeonpost-groupcrypto rust:1.91.1 \
#     sh -c 'cargo install wasm-bindgen-cli --version 0.2.128 --locked && scripts/build-wasm.sh'
#
#   cargo install wasm-bindgen-cli --version 0.2.128 --locked
#   crates/pigeonpost-groupcrypto/scripts/build-wasm.sh [--check]
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$here/../.." && pwd)"
out="$repo/site-inbox/vendor/groupcrypto"
want_bindgen="0.2.128"
have_bindgen="$(wasm-bindgen --version | awk '{print $2}')"
if [ "$have_bindgen" != "$want_bindgen" ]; then
  echo "wasm-bindgen-cli $want_bindgen required (found $have_bindgen)" >&2
  exit 1
fi
cargo_home="${CARGO_HOME:-$HOME/.cargo}"
export RUSTFLAGS="--remap-path-prefix=$cargo_home/registry/src=/cargo/registry/src --remap-path-prefix=$here=/groupcrypto --remap-path-prefix=$repo=/pigeonpost"
export CARGO_TARGET_DIR="$here/target/wasm-reproducible"
cd "$here"
cargo build --locked --release -p pigeonpost-groupcrypto-wasm --target wasm32-unknown-unknown
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
wasm-bindgen --target web --out-dir "$tmp" --out-name pigeonpost_groupcrypto \
  "$CARGO_TARGET_DIR/wasm32-unknown-unknown/release/pigeonpost_groupcrypto_wasm.wasm"
wasm_sha="$(shasum -a 256 "$tmp/pigeonpost_groupcrypto_bg.wasm" | awk '{print $1}')"
cat > "$tmp/integrity.js" <<JS
// Generated by crates/pigeonpost-groupcrypto/scripts/build-wasm.sh. Do not edit.
export const WASM_SHA256 = "$wasm_sha";
JS
if [ "$(uname -s)-$(uname -m)" != "Linux-x86_64" ]; then
  echo "note: the reference host is Linux x86_64; here only the JS glue is expected to match" >&2
fi
if [ "${1:-}" = "--check" ]; then
  status=0
  for f in pigeonpost_groupcrypto.js pigeonpost_groupcrypto_bg.wasm pigeonpost_groupcrypto.d.ts pigeonpost_groupcrypto_bg.wasm.d.ts integrity.js; do
    if ! cmp -s "$tmp/$f" "$out/$f"; then
      echo "::error::$f differs from a clean rebuild" >&2
      status=1
    fi
  done
  if [ $status -eq 0 ]; then
    echo "vendored bundle is reproducible (wasm sha256 $wasm_sha)"
  else
    # Keep the clean rebuild for inspection (CI uploads it).
    mkdir -p "$here/target/wasm-check" && cp "$tmp"/* "$here/target/wasm-check/"
    cp "$CARGO_TARGET_DIR/wasm32-unknown-unknown/release/pigeonpost_groupcrypto_wasm.wasm" "$here/target/wasm-check/raw.wasm"
  fi
  exit $status
fi
mkdir -p "$out"
cp "$tmp"/pigeonpost_groupcrypto.js "$tmp"/pigeonpost_groupcrypto_bg.wasm "$tmp"/pigeonpost_groupcrypto.d.ts \
  "$tmp"/pigeonpost_groupcrypto_bg.wasm.d.ts "$tmp"/integrity.js "$out/"
(cd "$out" && shasum -a 256 pigeonpost_groupcrypto.js pigeonpost_groupcrypto_bg.wasm integrity.js loader.js > SHA256SUMS)
echo "wrote $out (wasm sha256 $wasm_sha, $(wc -c < "$out/pigeonpost_groupcrypto_bg.wasm") bytes)"
